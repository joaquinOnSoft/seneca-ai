#!/bin/bash

# ==============================================================================
# Generate the Docker secrets used by the containers (only the missing ones).
#
#   docker/api/seneca_ai_api_key.txt      API key (X-SENECA-AI-API-KEY header)
#   docker/api/jwt_secret_key.txt         Signs the JWT access tokens
#   docker/mongo/mongo_root_username.txt  MongoDB root user
#   docker/mongo/mongo_root_password.txt  MongoDB root password
#
# Existing files are never overwritten:
#   · MongoDB only applies the root user/password when it initialises an EMPTY
#     data directory. A new password on an existing database would lock the
#     api container out.
#   · A new JWT secret would invalidate the tokens already issued.
#
# The API key is also copied to SENECA_AI_API_KEY in .env, so the desktop app
# uses the same key as the api container.
#
# None of these files is versioned (see .gitignore).
#
# Usage (from the project root):  source ./generate_secrets.sh
# ==============================================================================

SECRETS_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Random hexadecimal string: $1 bytes -> 2*$1 characters (safe in URIs and .env)
_random_hex() {
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
}

# Write $2 into file $1 (no trailing newline) unless it already has content.
# $3 = file mode.
_create_secret() {
    local file="$1" value="$2" mode="$3"
    if [ -s "$file" ]; then
        echo "Secret already exists, kept: $file"
        return
    fi
    mkdir -p "$(dirname "$file")"
    (umask 077 && printf '%s' "$value" > "$file")
    chmod "$mode" "$file"
    echo "Generated secret: $file"
}

# The api container runs as root, so its secrets can be private (600).
_create_secret "$SECRETS_ROOT/docker/api/seneca_ai_api_key.txt" "$(_random_hex 24)" 600
_create_secret "$SECRETS_ROOT/docker/api/jwt_secret_key.txt"    "$(_random_hex 32)" 600

# The mongo entrypoint switches to the "mongodb" user (uid 999) BEFORE reading
# the *_FILE variables, so these files must be readable by other users (644).
_create_secret "$SECRETS_ROOT/docker/mongo/mongo_root_username.txt" "senecaai_admin"    644
_create_secret "$SECRETS_ROOT/docker/mongo/mongo_root_password.txt" "$(_random_hex 24)" 644

# Keep SENECA_AI_API_KEY in .env in sync with the api container's key
_sync_env_api_key() {
    local env_file="$SECRETS_ROOT/.env"
    local key
    key="$(tr -d '\r\n' < "$SECRETS_ROOT/docker/api/seneca_ai_api_key.txt")"

    if [ ! -f "$env_file" ]; then
        cp "$SECRETS_ROOT/.env.example" "$env_file"
        echo "Created $env_file from .env.example"
    fi

    if grep -qxF "SENECA_AI_API_KEY=${key}" "$env_file"; then
        return
    fi
    if grep -q '^SENECA_AI_API_KEY=' "$env_file"; then
        # Escape the characters that are special in a sed replacement (\ | &),
        # in case the key was not generated by this script
        local escaped
        escaped="$(printf '%s' "$key" | sed 's/[\\|&]/\\&/g')"
        sed -i "s|^SENECA_AI_API_KEY=.*|SENECA_AI_API_KEY=${escaped}|" "$env_file"
    else
        printf '\nSENECA_AI_API_KEY=%s\n' "$key" >> "$env_file"
    fi
    echo "SENECA_AI_API_KEY updated in $env_file"
}
_sync_env_api_key

unset -f _random_hex _create_secret _sync_env_api_key
